import { expect, test } from '@playwright/test';
import { readFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { addCanvasNode, createProjectFromList } from './manual-studio';

test('素材岗位仅展示本轮产物，历史素材在手动画布中保持保存', async ({ page }) => {
  test.setTimeout(120000);
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/zh-CN/account');
  await page.getByTestId('auth-mode-register').click();
  await page.getByTestId('auth-email').fill(`material-browser-${crypto.randomUUID()}@example.com`);
  await page.getByTestId('auth-password').fill(crypto.randomUUID());
  await page.getByTestId('auth-submit').click();
  await expect(page).toHaveURL(/\/projects$/);
  await createProjectFromList(page, '素材岗位展示与引用验证');
  await expect(page).toHaveURL(/\/editor\?id=/);
  const id = new URL(page.url()).searchParams.get('id');
  const before = await (await page.request.get(`/api/v1/projects/${id}`)).json();
  const scene = before.project.graphData.nodes.find((node: { type: string }) => node.type === 'scene');
  const source = JSON.parse(await readFile(path.resolve('../.intermediate/agent-smoke/21c641f3-68a8-4ca3-8462-0e5ebc3f7508/first-turn.json'), 'utf8'));
  expect(source.messages[0].run.status).toBe('completed');
  expect(source.messages[0].run.calls.every((call: { model: string }) => call.model.includes('flash'))).toBe(true);
  const snapshots = source.nodes.map(({ contentHash, producerRole, ...node }: { contentHash: string; producerRole?: string; [key: string]: unknown }) => {
    expect(contentHash).toMatch(/^[a-f0-9]{64}$/);
    expect(producerRole === undefined || typeof producerRole === 'string').toBe(true);
    return node;
  });
  const saved = await page.request.put(`/api/v1/projects/${id}/canvases/${scene.id}`, { data: { expectedRevision: before.revision, operationId: crypto.randomUUID(), nodes: snapshots, connections: [], viewport: { x: 0, y: 0, k: 1 } } });
  expect(saved.status()).toBe(200);
  await page.reload();
  await page.getByTitle('素材', { exact: true }).click();
  await page.getByTestId('materials-generate-tab').click();
  const workspace = page.getByTestId('material-workspace');
  await expect(workspace.locator('[data-role]')).toHaveCount(6);
  await expect(page.getByTestId('material-chat')).toBeVisible();
  await expect(workspace.getByTestId('material-artifact')).toHaveCount(0);
  await expect(workspace.getByText('已有素材', { exact: true })).toHaveCount(0);
  const chat = page.getByTestId('material-chat');
  await chat.getByRole('textbox', { name: '素材需求' }).fill('把选中的场景改成清晨光线');
  await expect(chat).not.toContainText('¥');
  await expect(workspace).not.toContainText('供应商价格');
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await expect(chat.getByRole('textbox', { name: '素材需求' })).toBeInViewport();
    const directory = path.resolve('../docs/evidence/阶段2-2');
    await mkdir(directory, { recursive: true });
    await page.screenshot({ path: path.join(directory, `素材对话与岗位-${width}px.png`) });
  }
  await chat.getByRole('button', { name: '关闭素材对话' }).click();
  await workspace.getByRole('button', { name: '手动编辑画布' }).click();
  await expect(page.getByTestId('embedded-material-canvas').locator(`[data-testid="canvas-node"][data-node-id="${source.nodes[0].id}"]`)).toBeVisible();
  await expect(page.getByTestId('canvas-add-node')).toBeEnabled();
  await addCanvasNode(page, 'text');
  await workspace.getByRole('button', { name: '返回岗位展示' }).click();
  await expect(page.getByTestId('embedded-material-canvas')).toHaveCount(0);
  await expect(workspace.getByTestId('material-artifact')).toHaveCount(0);
  const after = await (await page.request.get(`/api/v1/projects/${id}`)).json();
  expect(after.project.graphData.edges).toEqual(before.project.graphData.edges);
  const contentNodes = (nodes: { id: string; type: string; data: unknown; position: unknown }[]) => nodes.map(({ id, type, data, position }) => ({ id, type, data, position }));
  expect(contentNodes(after.project.graphData.nodes)).toEqual(contentNodes(before.project.graphData.nodes));
  expect(after.canvases.find((canvas: { sceneId: string }) => canvas.sceneId === scene.id).nodes).toHaveLength(snapshots.length + 1);
  const listPath = `/api/v1/projects/${id}/scenes/${scene.id}/material-conversations`;
  expect((await (await page.request.get(listPath)).json()).conversations).toHaveLength(1);
  await page.reload();
  await page.getByTitle('素材', { exact: true }).click();
  await page.getByTestId('materials-generate-tab').click();
  await expect(page.getByTestId('material-artifact')).toHaveCount(0);
  expect((await (await page.request.get(listPath)).json()).conversations).toHaveLength(1);
  await page.getByRole('button', { name: '新建素材对话' }).click();
  await expect(page.getByRole('combobox', { name: '素材对话记录' }).locator('option')).toHaveCount(2);
  expect((await (await page.request.get(listPath)).json()).conversations).toHaveLength(2);
  await expect(page.getByTestId('material-artifact')).toHaveCount(0);
  expect(errors).toEqual([]);
});
