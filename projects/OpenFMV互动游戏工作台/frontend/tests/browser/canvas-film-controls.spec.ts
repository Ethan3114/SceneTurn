import { expect, test, type Locator, type Page } from '@playwright/test';
import path from 'node:path';
import { addCanvasNode, createProjectFromList, enterManualStudio } from './manual-studio';

test.use({ viewport: { width: 1600, height: 1100 } });

async function enterProject(page: Page, name: string) {
  await page.goto('/zh-CN/account');
  await page.getByTestId('auth-mode-register').click();
  await page.getByTestId('auth-email').fill('film-' + crypto.randomUUID() + '@example.com');
  await page.getByTestId('auth-password').fill(crypto.randomUUID());
  await page.getByTestId('auth-submit').click();
  await expect(page).toHaveURL(/\/projects$/);
  await createProjectFromList(page, name);
  await enterManualStudio(page);
}

async function selectCenter(page: Page, preview: Locator) {
  const rect = await preview.boundingBox();
  if (!rect) throw new Error('缺少裁切预览');
  await page.mouse.move(rect.x + rect.width * .25, rect.y + rect.height * .25);
  await page.mouse.down();
  await page.mouse.move(rect.x + rect.width * .75, rect.y + rect.height * .75, { steps: 6 });
  await page.mouse.up();
}

test('首尾帧预设、影视指导和节点声音进入实际视频核对记录', async ({ page }) => {
  await enterProject(page, '影视指导与首尾帧');
  const video = await addCanvasNode(page, 'video');
  const id = await video.getAttribute('data-node-id');
  const projectId = new URL(page.url()).searchParams.get('id');
  await video.getByRole('button', { name:'首尾帧生成视频', exact:true }).click();
  const config = page.locator('[data-node-id="' + id + '"][data-testid="canvas-node"]');
  await expect(config.getByTestId('generation-source-first').locator('img')).toHaveCount(1);
  await expect(config.getByTestId('generation-source-last').locator('img')).toHaveCount(1);
  const wrapped = await (await page.request.get('/api/v1/projects/' + projectId)).json();
  const members = wrapped.canvases[0].nodes as {id:string; type:string; title:string; metadata?:{groupId?:string}}[];
  const group = members.find(item => item.type === 'group' && item.title === '预设 - 首尾帧生成视频');
  expect(group).toBeDefined();
  expect(members.filter(item => item.metadata?.groupId === group!.id)).toHaveLength(3);
  await config.getByRole('button', { name:'配色', exact:true }).click();
  const gallery = page.getByRole('dialog', { name:'配色库' });
  await gallery.getByLabel('搜索配色').fill('月光蓝');
  await gallery.getByRole('button', { name:'月光蓝色调', exact:true }).click();
  await gallery.getByRole('button', { name:'确定' }).click();
  await config.getByRole('button', { name:'相机', exact:true }).click();
  const camera = page.getByRole('dialog', { name:'相机设置' });
  await camera.getByLabel('焦距', { exact:true }).selectOption('35mm');
  await camera.getByRole('button', { name:'确认' }).click();
  await config.getByRole('button', { name:'节奏', exact:true }).click();
  const rhythm = page.getByRole('dialog', { name:'节奏库' });
  await expect(rhythm.locator('video')).toBeVisible();
  await rhythm.getByRole('button', { name:'下一段' }).click();
  await rhythm.getByRole('button', { name:'取消' }).click();
  await config.getByRole('button', { name:'预设提示词' }).click();
  const library = page.getByRole('dialog', { name:'提示词库' });
  await library.getByLabel('搜索提示词').fill('真实物理');
  await library.getByRole('button', { name:/真实物理运动/ }).first().click();
  await library.getByRole('button', { name:'确定' }).click();
  await expect(config.getByTestId('generation-prompt')).toContainText('人物动作遵循重力');
  await config.getByRole('button', { name:'生成声音' }).click();
  await page.getByTestId('canvas-save').click();
  await expect(page.getByTestId('save-status')).toContainText('已保存');
  await page.reload();
  await config.getByTestId('canvas-node-title').click();
  await expect(config.getByRole('button', { name:'配色', exact:true })).toHaveText('月光蓝色调');
  await expect(config.getByRole('button', { name:'生成声音' })).toHaveAttribute('aria-pressed', 'false');
  await config.getByTestId('generation-quote').click();
  await expect.poll(async () => (await (await page.request.get('/api/v1/projects/' + projectId + '/generations')).json()).generations.length).toBe(1);
  const { generations } = await (await page.request.get('/api/v1/projects/' + projectId + '/generations')).json();
  expect(generations[0]).toMatchObject({ status:'awaiting_confirmation', remoteTaskId:null, reservedCents:0, input:{ audio:false } });
  expect(generations[0].input.prompt).toContain('配色：月光蓝色调');
  expect(generations[0].input.prompt).toContain('焦距：35mm');
  expect(generations[0].input.prompt).not.toContain('节奏：');
  expect(generations[0].input.canvasMedia.map((item:{type:string}) => item.type)).toEqual(['first_frame','last_frame']);
});

test('真实视频抽帧、截取片段，裁切抽取画面并保留原素材连线', async ({ page }) => {
  await enterProject(page, '成片工具');
  const projectId = new URL(page.url()).searchParams.get('id');
  const getProject = async () => (await (await page.request.get('/api/v1/projects/' + projectId)).json());
  await page.getByTestId('canvas-import-file').setInputFiles(path.resolve(process.cwd(),'public/sceneturn/canvas/guidance/rhythm-0.mp4'));
  const source = page.getByTestId('canvas-node').first();
  await expect(source.getByRole('button', { name:'提取帧' })).toBeVisible();
  await source.getByRole('button', { name:'提取帧' }).click();
  await source.getByRole('button', { name:'提取尾帧' }).click();
  const frameDialog=page.getByRole('dialog', { name:'提取尾帧' });
  await frameDialog.getByRole('button', {name:'保存到画布'}).click();
  await expect(frameDialog).toHaveCount(0);
  const frame=page.getByTestId('canvas-node').nth(1);
  await frame.getByTestId('canvas-node-title').click();
  await frame.getByRole('button', { name:'裁切', exact:true }).click();
  const crop=page.getByRole('dialog', { name:'裁切' });
  await selectCenter(page, crop.locator('img'));
  await crop.getByRole('button', {name:'保存到画布'}).click();
  await expect(crop).toHaveCount(0);
  await source.getByTestId('canvas-node-title').click();
  await source.getByRole('button', {name:'截取片段'}).click();
  const clip=page.getByRole('dialog',{name:'截取片段'});
  await clip.getByLabel('入点（秒）').fill('1');
  await clip.getByLabel('出点（秒）').fill('2');
  await clip.getByRole('button',{name:'保存到画布'}).click();
  await expect(clip).toHaveCount(0);
  const saved=await getProject();
  expect(saved.project.assets).toHaveLength(4);
  expect(saved.canvases[0].connections).toHaveLength(3);
  expect(saved.project.assets[1].metadata).toMatchObject({width:512,height:288});
  expect(saved.project.assets[2].metadata.width).toBeLessThan(260);
  expect(saved.project.assets[3].metadata).toMatchObject({width:512,height:288,duration:1});
  await source.getByTestId('canvas-node-title').click();
  await source.getByRole('button', { name: '更多', exact: true }).click();
  await source.getByRole('button', { name: '裁切', exact: true }).click();
  const videoCrop = page.getByRole('dialog', { name: '裁切' });
  await expect.poll(() => videoCrop.locator('video').evaluate(el => (el as HTMLVideoElement).videoWidth)).toBe(512);
  await videoCrop.locator('video').scrollIntoViewIfNeeded();
  const previewSize = await videoCrop.locator('video').boundingBox();
  await selectCenter(page, videoCrop.locator('video'));
  const selectedSize = await videoCrop.locator('.fmv-result-rect').boundingBox();
  expect(previewSize).toBeTruthy();
  expect(selectedSize).toBeTruthy();
  const desiredWidth = Math.floor(512 * selectedSize!.width / previewSize!.width / 2) * 2;
  const desiredHeight = Math.floor(288 * selectedSize!.height / previewSize!.height / 2) * 2;
  await videoCrop.getByRole('button', { name: '保存到画布' }).click();
  await expect(videoCrop).toHaveCount(0);
  const complete = await getProject();
  const output = complete.project.assets[4];
  expect(output.type).toBe('video');
  expect(desiredWidth).toBeGreaterThan(251);
  expect(desiredWidth).toBeLessThan(260);
  expect(desiredHeight).toBeGreaterThan(140);
  expect(desiredHeight).toBeLessThan(149);
  expect(Math.abs(output.metadata.width - desiredWidth)).toBeLessThanOrEqual(2);
  expect(Math.abs(output.metadata.height - desiredHeight)).toBeLessThanOrEqual(2);
  expect(output.metadata.duration).toBeCloseTo(complete.project.assets[0].metadata.duration, 1);
  expect(complete.canvases[0].connections).toHaveLength(4);
});
