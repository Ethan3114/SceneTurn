import { expect, test } from '@playwright/test';
import path from 'node:path';

test('手动画布保留素材、节点版本、对话引用和视图操作', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 960 });
  const registration = await page.request.post('/api/v1/auth/register', { data: { email: `canvas-browser-${crypto.randomUUID()}@example.com`, password: crypto.randomUUID() } });
  expect(registration.ok()).toBe(true);
  const projectResponse = await page.request.post('/api/v1/projects', { data: { title: '素材画布工具检查' } });
  expect(projectResponse.ok()).toBe(true);
  const { project } = await projectResponse.json();
  const scene = project.graphData.nodes.find((n: { type: string }) => n.type === 'scene');
  await page.goto(`/zh-CN/studio?id=${project.id}&sceneId=${scene.id}`);
  const add = page.getByTestId('canvas-add-node');
  await expect(add).toBeEnabled();
  await add.click();
  await expect(page.getByTestId('canvas-create-director')).toBeEnabled();
  await page.getByTestId('canvas-create-upload').click();
  await page.getByTestId('canvas-import-file').setInputFiles({ name: '对白.txt', mimeType: 'text/plain', buffer: Buffer.from('夜风经过窗台。') });
  const node = page.getByTestId('canvas-node').first();
  await expect(node).toContainText('对白.txt');
  await page.getByTestId('canvas-save').click();
  await expect(page.getByTestId('save-status')).toContainText('已保存');
  const actions = page.getByTestId('canvas-node-actions');
  await actions.getByRole('button', { name:'版本记录' }).click();
  const versions = page.getByRole('dialog', {name:'版本记录'});
  await expect(versions.getByText('夜风经过窗台。')).toBeVisible();
  await versions.getByRole('button', { name:'关闭' }).click();
  await actions.getByRole('button', { name:'创建资产' }).click();
  const save = page.getByRole('dialog', {name:'创建资产'});
  await save.getByLabel('资产名称').fill('夜风台词'); await save.getByLabel('文件夹').fill('第一场');
  await save.getByRole('button', { name:'保存到资产库' }).click();
  await expect(save).toHaveCount(0);
  await page.getByRole('button', { name:'素材库', exact:true }).click();
  const browser = page.getByRole('complementary', {name:'资产管理'});
  await browser.getByRole('button',{name:'已保存',exact:true}).click();
  await browser.getByLabel('资产文件夹').selectOption('第一场');
  await expect(browser.getByRole('button',{name:'夜风台词'})).toBeVisible();
  await browser.getByLabel('展开资产管理器').click();
  await expect(browser).toHaveAttribute('data-expanded','true');
  await browser.getByLabel('收起节点侧栏').click();
  await page.getByRole('button',{name:'节点列表',exact:true}).click();
  await browser.getByLabel('筛选类型').selectOption('video');
  await expect(browser).toContainText('没有符合条件');
  await browser.getByLabel('筛选类型').selectOption('text');
  await browser.getByRole('searchbox',{name:'搜索节点'}).fill('对白');
  await browser.getByLabel('网格视图').click();
  await browser.getByRole('button',{name:'对白.txt'}).click();
  await browser.getByLabel('收起节点侧栏').click();
  await page.getByLabel('缩放选项',{exact:true}).click();
  await page.getByRole('spinbutton',{name:'缩放百分比'}).fill('85');
  await page.getByRole('spinbutton',{name:'缩放百分比'}).press('Enter');
  await expect(page.getByRole('button',{name:'缩放选项'})).toHaveText('85%');
  const surface = page.getByTestId('canvas-surface');
  await surface.focus();
  await expect(surface).toHaveCSS('cursor','grab');
  await surface.press('?');
  const shortcuts = page.getByRole('dialog',{name:'快捷键'});
  await expect(shortcuts).toContainText('平移视野');
  await expect(shortcuts).toContainText('长按节点后拖动');
  await page.keyboard.press('Escape');
  await actions.getByRole('button',{name:'发送到创作对话'}).click();
  const chat = page.getByTestId('material-chat');
  await expect(chat.getByRole('button',{name:'移除引用 对白.txt'})).toBeVisible();
  if (process.env.OPENFMV_CAPTURE_CANVAS === '1') {
    await page.screenshot({ path: path.resolve('../docs/evidence/阶段3-1/手动画布与素材对话-1440px.png') });
  }
  await chat.getByRole('button',{name:'管理对话'}).click();
  await chat.getByLabel('当前对话名称').fill('镜头修改');
  await chat.getByRole('button',{name:'保存名称'}).click();
  await expect(chat.getByRole('button',{name:'镜头修改',exact:true})).toBeVisible();
  await chat.getByRole('button',{name:'关闭素材对话'}).click();
  await page.getByRole('button',{name:'故事板',exact:true}).click();
  await page.getByRole('button',{name:'角色',exact:true}).click();
  await expect(page.getByRole('region',{name:'故事板'})).toContainText('当前分类暂无素材');
  await page.getByRole('button',{name:'工作流',exact:true}).click();
  await expect(node).toContainText('对白.txt');
  await page.reload();
  await expect(page.getByTestId('canvas-node').first()).toContainText('对白.txt');
  await page.getByRole('button', {name:'创作广场'}).click();
  const character = page.getByRole('dialog', {name:'角色造型室'});
  await character.getByLabel('角色名称').fill('送信人');
  await character.getByLabel('服装').fill('蓝布外套，肩上挎着帆布包');
  await character.getByRole('button', {name:'添加到画布'}).click();
  await expect(page.getByTestId('canvas-node-title').filter({hasText:'送信人'})).toBeVisible();
  await page.getByTestId('canvas-save').click();
  await expect(page.getByTestId('save-status')).toContainText('已保存');
  await page.getByRole('button', {name:'全部功能'}).click();
  const tools = page.getByRole('dialog', {name:'全部功能'});
  await tools.getByRole('searchbox', {name:'搜索工具'}).fill('裁切');
  await tools.getByRole('button', {name:'裁切',exact:true}).click();
  await expect(tools).toContainText('请先从添加菜单上传图片');
  await tools.getByRole('button', {name:'全部功能'}).click();
  await tools.getByRole('button',{name:'关闭'}).click();
  await page.getByRole('button',{name:'教程',exact:true}).click();
  const guide = page.getByRole('link',{name:'使用教程'});
  const guideUrl = await guide.getAttribute('href');
  expect(guideUrl).toBeTruthy();
  expect((await page.request.get(guideUrl!)).status()).toBe(200);
});
